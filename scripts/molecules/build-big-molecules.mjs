#!/usr/bin/env node
// The chart's big molecules for the Hopf pictures (public/hopf/hopf-core.js), too
// many atoms to treat one by one, so the work is done here once: each structure
// from the Protein Data Bank (scripts/molecules/pdb.mjs), turned to its principal
// axes, reduced to
//   chains  each chain's backbone, the CA of every amino acid or the P of every
//           nucleotide (Å), drawn as glowing tubes
//   marks   landmark atoms drawn larger (hemoglobin's irons, insulin's zincs)
//   dots    the atoms drawn as small glows (at most DOTS, evenly sampled), in their elements' colours
// and written to public/hopf/big-molecules.js. DNA is an ideal B-form helix of
// 36 base pairs built here (the 12-pair crystal is barely one turn).
//
//   node scripts/molecules/build-big-molecules.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { cifOf, atomsOf, orient } from "./pdb.mjs";

const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "../../public/hopf/big-molecules.js");
const DOTS = 2500;
const MARKS = new Set(["FE", "ZN"]);
// chart slug → structure; chains: keep only those (one copy of a crystal that holds two)
const SUBJECTS = {
  insulin: { pdb: "4INS" },
  hemoglobin: { pdb: "4HHB" },
  "antibody-igg": { pdb: "1IGT" },
  ribosome: { pdb: "4YBB", chains: /^[AD]/ },
};

// ideal B-DNA: 10 base pairs a turn (36°), 3.38 Å rise, phosphates at 8.9 Å from the
// axis, the bases' sugars at 5.9 Å; the two strands' phosphates of a pair ~155° apart
function bDNA(pairs) {
  const atoms = [], rad = d => d * Math.PI / 180, at = (r, deg, z) => [r * Math.cos(rad(deg)), r * Math.sin(rad(deg)), z];
  for (let i = 0; i < pairs; i++) {
    const th = 36 * i, z = 3.38 * (i - (pairs - 1) / 2);
    atoms.push({ el: "P", name: "P", chain: "A", seq: i, p: at(8.9, th, z) }, { el: "P", name: "P", chain: "B", seq: pairs - i, p: at(8.9, th + 155, z) });
    const a = at(5.9, th + 20, z), b = at(5.9, th + 135, z);
    atoms.push({ el: "C", name: "C1'", chain: "A", seq: i, p: a }, { el: "C", name: "C1'", chain: "B", seq: pairs - i, p: b });
    // the base pair: a flat rung of ~20 atoms between the two sugars
    for (let k = 1; k < 10; k++) for (const s of [-0.6, 0.6]) {
      const t = k / 10, p = a.map((v, j) => v + (b[j] - v) * t);
      atoms.push({ el: k % 3 ? "C" : "N", name: "B", chain: "base", seq: i, p: [p[0] + s * 0.8 * Math.sin(rad(th)), p[1] - s * 0.8 * Math.cos(rad(th)), p[2]] });
    }
  }
  return atoms;
}

function pack(atoms, backbone) {
  orient(atoms);
  let R = 0;
  for (const a of atoms) R = Math.max(R, Math.hypot(...a.q));
  R += 3;
  const r1 = v => Math.round(v * 10) / 10;
  const chains = [];
  for (const ch of new Set(atoms.map(a => a.chain))) {
    const bb = atoms.filter(a => a.chain === ch && backbone.includes(a.name) && !a.het).sort((a, b) => a.seq - b.seq);
    // a gap over 8 Å (a missing stretch) starts a new piece
    let piece = [];
    for (const a of bb) {
      if (piece.length && Math.hypot(...a.q.map((v, k) => v - piece[piece.length - 1][k])) > 8) { if (piece.length > 2) chains.push({ kind: a.name === "P" ? "nucleic" : "protein", pts: piece.flat().map(r1) }); piece = []; }
      piece.push(a.q);
    }
    if (piece.length > 2) chains.push({ kind: bb[0].name === "P" ? "nucleic" : "protein", pts: piece.flat().map(r1) });
  }
  const step = Math.max(1, Math.floor(atoms.length / DOTS));
  return {
    R: r1(R), chains,
    marks: atoms.filter(a => MARKS.has(a.el)).map(a => [a.el, ...a.q.map(r1)]),
    dots: atoms.filter((a, i) => i % step === 0 && !MARKS.has(a.el)).map(a => [a.el, ...a.q.map(r1)]),
    atoms: atoms.length,
  };
}

const BIG = { dna: pack(bDNA(36), ["P"]) };
for (const [slug, s] of Object.entries(SUBJECTS)) {
  const atoms = atomsOf(await cifOf(s.pdb)).filter(a => !s.chains || s.chains.test(a.chain));
  BIG[slug] = pack(atoms, ["CA", "P"]);
}
fs.writeFileSync(OUT, `// The chart's big molecules for the Hopf pictures: backbones, landmark atoms and up to
// 2,500 atoms. Generated by scripts/molecules/build-big-molecules.mjs
// from the Protein Data Bank (DNA: an ideal B-form helix); don't edit by hand.
export const BIG = ${JSON.stringify(BIG)};
`);
for (const [s, m] of Object.entries(BIG)) console.log(`${s}: ${m.atoms} atoms, R ${m.R} Å, ${m.chains.length} backbone pieces, ${m.marks.length} marks, ${m.dots.length} dots`);
console.log(`${(fs.statSync(OUT).size / 1024).toFixed(0)} KB`);
