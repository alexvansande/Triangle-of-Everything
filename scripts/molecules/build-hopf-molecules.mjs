#!/usr/bin/env node
// The chart's small molecules as 3D atom positions for the Hopf pictures
// (public/hopf/hopf-core.js): fetches each one's 3D conformer from PubChem
// (cached in scripts/molecules/sdf/), builds C₆₀ from its geometry, and writes
// public/hopf/molecules.js: { slug: [[element, x, y, z] (Å), …] }, centred.
//
//   node scripts/molecules/build-hopf-molecules.mjs          # uses the cache
//   node scripts/molecules/build-hopf-molecules.mjs --fetch  # refreshes it
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SDF = path.join(HERE, "sdf"), OUT = path.join(HERE, "../../public/hopf/molecules.js");
// chart slug → PubChem compound (3D conformer)
const PUBCHEM = {
  glucose: 64689,          // β-D-glucopyranose, the ring form glucose takes in water
  "adenine-a": 190, "guanine-g": 135398634, "cytosine-c": 597, "thymine-t": 1135,
  atp: 5957,
};

async function sdfOf(slug, cid) {
  const file = path.join(SDF, `${slug}.sdf`);
  if (!process.argv.includes("--fetch") && fs.existsSync(file)) return fs.readFileSync(file, "utf8");
  const res = await fetch(`https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/cid/${cid}/record/SDF?record_type=3d`);
  if (!res.ok) throw Error(`PubChem ${cid}: ${res.status}`);
  const text = await res.text();
  fs.mkdirSync(SDF, { recursive: true });
  fs.writeFileSync(file, text);
  return text;
}
// V2000 molfile: counts on line 4, then one atom per line (x y z element)
function atomsOf(sdf) {
  const lines = sdf.split("\n"), n = parseInt(lines[3].slice(0, 3));
  return lines.slice(4, 4 + n).map(l => { const f = l.trim().split(/\s+/); return [f[3], +f[0], +f[1], +f[2]]; });
}
// C₆₀: an icosahedron's 30 edges each give the points 1/3 and 2/3 along them,
// scaled so the bonds average 1.42 Å (the real ones alternate 1.40 and 1.45)
function fullerene() {
  const p = (1 + Math.sqrt(5)) / 2;
  const v = [[0, 1, p], [0, -1, p], [0, 1, -p], [0, -1, -p], [1, p, 0], [-1, p, 0], [1, -p, 0], [-1, -p, 0], [p, 0, 1], [p, 0, -1], [-p, 0, 1], [-p, 0, -1]];
  const d = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2]);
  const out = [];
  for (let i = 0; i < 12; i++) for (let j = i + 1; j < 12; j++) if (Math.abs(d(v[i], v[j]) - 2) < 1e-6)
    for (const t of [1 / 3, 2 / 3]) out.push(v[i].map((c, k) => c + (v[j][k] - c) * t));
  const k = 1.42 / (2 / 3);    // icosahedron edge 2 → truncated edge 2/3
  return out.map(q => ["C", ...q.map(c => c * k)]);
}
// centred and turned to its principal axes: the long one across, the next one up,
// the thinnest toward the viewer, so a flat ring faces the camera, not its edge
function centred(atoms) {
  const m = [1, 2, 3].map(k => atoms.reduce((s, a) => s + a[k], 0) / atoms.length);
  const P = atoms.map(a => [a[1] - m[0], a[2] - m[1], a[3] - m[2]]);
  const C = [0, 1, 2].map(i => [0, 1, 2].map(j => P.reduce((s, p) => s + p[i] * p[j], 0)));
  // Jacobi rotations until C is diagonal; V's columns are the axes
  const V = [[1, 0, 0], [0, 1, 0], [0, 0, 1]];
  for (let sweep = 0; sweep < 50; sweep++) for (const [p, q] of [[0, 1], [0, 2], [1, 2]]) {
    if (Math.abs(C[p][q]) < 1e-12) continue;
    const th = 0.5 * Math.atan2(2 * C[p][q], C[q][q] - C[p][p]), c = Math.cos(th), s = Math.sin(th);
    for (let k = 0; k < 3; k++) { const a = C[k][p], b = C[k][q]; C[k][p] = c * a - s * b; C[k][q] = s * a + c * b; }
    for (let k = 0; k < 3; k++) { const a = C[p][k], b = C[q][k]; C[p][k] = c * a - s * b; C[q][k] = s * a + c * b; }
    for (let k = 0; k < 3; k++) { const a = V[k][p], b = V[k][q]; V[k][p] = c * a - s * b; V[k][q] = s * a + c * b; }
  }
  const order = [0, 1, 2].sort((i, j) => C[j][j] - C[i][i]);   // widest first
  const axes = order.map(i => [V[0][i], V[1][i], V[2][i]]);
  // a proper rotation (no mirror image): the third axis is the cross product of the first two
  const [u, v] = axes;
  axes[2] = [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]];
  return atoms.map((a, k) => [a[0], ...axes.map(ax => +(ax[0] * P[k][0] + ax[1] * P[k][1] + ax[2] * P[k][2]).toFixed(3))]);
}

const molecules = {};
for (const [slug, cid] of Object.entries(PUBCHEM)) molecules[slug] = centred(atomsOf(await sdfOf(slug, cid)));
molecules["fullerene-c60"] = centred(fullerene());
fs.writeFileSync(OUT, `// The chart's small molecules, atom positions in Å (centred), for the Hopf
// pictures. Generated by scripts/molecules/build-hopf-molecules.mjs from PubChem's
// 3D conformers (C₆₀ from its geometry); don't edit by hand.
export const MOLECULES = ${JSON.stringify(molecules).replace(/\],\[/g, "],\n  [")};
`);
for (const [s, a] of Object.entries(molecules)) console.log(`${s}: ${a.length} atoms (${[...new Set(a.map(x => x[0]))].join(" ")})`);
